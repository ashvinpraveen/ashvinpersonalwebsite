import { get } from "@vercel/blob";
import { createWriteStream, existsSync, readFileSync } from "node:fs";
import { mkdir, open, rename, rm, writeFile } from "node:fs/promises";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import {
  SERIF_FALLBACKS,
  SANS_FALLBACKS,
  TIMELESS_BLOB_PREFIX,
  TIMELESS_FILENAMES,
  timelessFontPath,
  timelessFontsReady,
  timelessLoadModulePath,
} from "../src/lib/timeless-fonts.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const stagingDir = join(root, "src/fonts/timeless/.staging");
const quoteFamily = (name) => (name.includes(" ") ? `"${name}"` : name);
const fallbackList = `Body falls back to ${SANS_FALLBACKS.map(quoteFamily).join(", ")}. Display falls back to the same stack, then ${SERIF_FALLBACKS.map(quoteFamily).join(", ")}.`;

loadEnvFiles();

try {
  await fetchTimelessFonts();
} catch (error) {
  await rm(stagingDir, { recursive: true, force: true });
  const reason = publicReason(error);
  if (timelessFontsReady()) {
    console.warn(
      `[fonts] Timeless could not be downloaded (${reason}). Using the copies already in src/fonts/timeless/.`,
    );
  } else {
    await removePartialFonts();
    console.warn(`[fonts] Timeless could not be downloaded (${reason}). ${fallbackList}`);
  }
}

await writeLoadModule();

async function fetchTimelessFonts() {
  const token = process.env.BLOB_READ_WRITE_TOKEN?.trim();
  if (!token) {
    if (timelessFontsReady()) {
      console.warn(
        "[fonts] BLOB_READ_WRITE_TOKEN is not set. Using Timeless files already present in src/fonts/timeless/.",
      );
      return;
    }
    console.warn(
      `[fonts] BLOB_READ_WRITE_TOKEN is not set. Timeless will not be embedded. ${fallbackList}`,
    );
    await removePartialFonts();
    return;
  }

  await rm(stagingDir, { recursive: true, force: true });
  await mkdir(stagingDir, { recursive: true });
  const downloads = await Promise.allSettled(
    TIMELESS_FILENAMES.map((filename) => downloadFont(filename, token)),
  );
  const failed = downloads.find((result) => result.status === "rejected");
  if (failed && failed.status === "rejected") throw failed.reason;
  await mkdir(dirname(timelessFontPath(TIMELESS_FILENAMES[0])), { recursive: true });
  for (const filename of TIMELESS_FILENAMES) {
    await rename(join(stagingDir, filename), timelessFontPath(filename));
  }
  await rm(stagingDir, { recursive: true, force: true });
}

async function downloadFont(filename, token) {
  const pathname = `${TIMELESS_BLOB_PREFIX}/${filename}`;
  const result = await get(pathname, { access: "private", token, useCache: false });
  if (!result || result.statusCode !== 200 || !result.stream) {
    throw new Error(`${filename} is missing from the private store`);
  }
  const destination = join(stagingDir, filename);
  await pipeline(Readable.fromWeb(result.stream), createWriteStream(destination));
  if (!(await hasWoff2Signature(destination))) {
    throw new Error(`${filename} is not a woff2 font`);
  }
}

async function hasWoff2Signature(file) {
  const handle = await open(file, "r");
  try {
    const bytes = new Uint8Array(4);
    const { bytesRead } = await handle.read(bytes, 0, 4, 0);
    return bytesRead === 4 && String.fromCharCode(...bytes) === "wOF2";
  } finally {
    await handle.close();
  }
}

async function removePartialFonts() {
  await Promise.all(
    TIMELESS_FILENAMES.map((filename) => rm(timelessFontPath(filename), { force: true })),
  );
}

async function writeLoadModule() {
  const path = timelessLoadModulePath();
  await mkdir(dirname(path), { recursive: true });
  const source = timelessFontsReady() ? activeLoadModule() : fallbackLoadModule();
  const current = existsSync(path) ? readFileSync(path, "utf8") : "";
  if (current === source) return;
  const temporary = `${path}.tmp`;
  await writeFile(temporary, source);
  await rename(temporary, path);
}

function fallbackLoadModule() {
  return `/** Generated by scripts/fetch-fonts.mjs. Timeless files are absent, so the site keeps DM Sans. */
export const timelessReady = false;
export const timelessVariableClassName = "";
`;
}

function activeLoadModule() {
  return `/** Generated by scripts/fetch-fonts.mjs. Do not commit this copy: it points at gitignored font files. */
import localFont from "next/font/local";

const timelessSerif = localFont({
  src: [
    { path: "./TimelessSerifVF.woff2", weight: "100 900", style: "normal" },
    { path: "./TimelessSerifItalicVF.woff2", weight: "100 900", style: "italic" },
  ],
  variable: "--font-timeless-serif",
  display: "swap",
  adjustFontFallback: "Times New Roman",
  fallback: ["Georgia", '"Iowan Old Style"', '"Times New Roman"', "serif"],
  declarations: [{ prop: "font-variation-settings", value: '"STYL" 100' }],
});

const timelessSans = localFont({
  src: [
    { path: "./TimelessSansVF.woff2", weight: "100 900", style: "normal" },
    { path: "./TimelessSansVF.woff2", weight: "100 900", style: "italic" },
  ],
  variable: "--font-timeless-sans",
  display: "swap",
  fallback: ["system-ui", "sans-serif"],
  declarations: [{ prop: "font-variation-settings", value: '"STYL" 0' }],
});

export const timelessReady = true;
export const timelessVariableClassName = \`\${timelessSerif.variable} \${timelessSans.variable}\`;
`;
}

function loadEnvFiles() {
  const preexisting = new Set(Object.keys(process.env));
  for (const filename of [".env", ".env.local"]) {
    const path = join(root, filename);
    if (!existsSync(path)) continue;
    for (const line of readFileSync(path, "utf8").split("\n")) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith("#")) continue;
      const eq = trimmed.indexOf("=");
      if (eq <= 0) continue;
      const key = trimmed.slice(0, eq).trim();
      if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) || preexisting.has(key)) continue;
      let value = trimmed.slice(eq + 1).trim();
      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1);
      }
      process.env[key] = value;
    }
  }
}

function publicReason(error) {
  const raw = error instanceof Error ? error.message : "download failed";
  const redacted = raw
    .replace(/https?:\/\/\S+/g, "[url]")
    .replace(/vercel_blob_\S+/g, "[token]")
    .replace(/Bearer\s+\S+/g, "Bearer [token]");
  const clipped = redacted.replace(/\s+/g, " ").trim().slice(0, 180);
  return clipped || "download failed";
}
