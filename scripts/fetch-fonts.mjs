function writeFallbackModule() {
  writeIfChanged(
    generatedPath,
    `/* Generated by scripts/fetch-fonts.mjs. Do not edit. */
import { DM_Sans } from "next/font/google";

const dmSans = DM_Sans({
  subsets: ["latin"],
  style: ["normal", "italic"],
  axes: ["opsz"],
  display: "swap",
  variable: "--font-dm-sans",
});

export const fontClassName = dmSans.variable;
`,
  );
}

function writeIfChanged(path, contents) {
  if (existsSync(path) && readFileSync(path, "utf8") === contents) return;
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, contents);
}

function fontPath(filename) {
  return join(fontDir, filename);
}

function fontsReady() {
  return filenames.every((filename) => isWoff2(fontPath(filename)));
}

function fontsAreFresh() {
  const now = Date.now();
  return filenames.every((filename) => {
    try {
      return now - statSync(fontPath(filename)).mtimeMs < freshMs;
    } catch {
      return false;
    }
  });
}

function isWoff2(file) {
  try {
    if (statSync(file).size < 256) return false;
    const handle = openSync(file, "r");
    try {
      const bytes = new Uint8Array(4);
      readSync(handle, bytes, 0, 4, 0);
      return String.fromCharCode(...bytes) === "wOF2";
    } finally {
      closeSync(handle);
    }
  } catch {
    return false;
  }
}

async function hasWoff2Signature(file) {
  const handle = await open(file, "r");
  try {
    const bytes = new Uint8Array(4);
    const { bytesRead } = await handle.read(bytes, 0, 4, 0);
    return bytesRead === 4 && String.fromCharCode(...bytes) === "wOF2";
  } finally {
    await handle.close();
  }
}

async function removePartialFonts() {
  await Promise.all(filenames.map((filename) => rm(fontPath(filename), { force: true })));
}

function readState() {
  if (!existsSync(statePath)) return "";
  return readFileSync(statePath, "utf8");
}

function note(state, warning) {
  if (readState() === state) return;
  mkdirSync(dirname(statePath), { recursive: true });
  writeFileSync(statePath, state);
  if (warning) console.warn(warning);
}

function loadEnvFiles() {
  const preexisting = new Set(Object.keys(process.env));
  for (const filename of [".env", ".env.local"]) {
    const path = join(root, filename);
    if (!existsSync(path)) continue;
    for (const line of readFileSync(path, "utf8").split("\n")) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith("#")) continue;
      const eq = trimmed.indexOf("=");
      if (eq <= 0) continue;
      const key = trimmed.slice(0, eq).trim();
      if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(key) || preexisting.has(key)) continue;
      let value = trimmed.slice(eq + 1).trim();
      if (
        (value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))
      ) {
        value = value.slice(1, -1);
      }
      process.env[key] = value;
    }
  }
}

function publicReason(error) {
  const raw = error instanceof Error ? error.message : "download failed";
  const redacted = raw
    .replace(/https?:\/\/\S+/g, "[url]")
    .replace(/vercel_blob_\S+/g, "[token]")
    .replace(/Bearer\s+\S+/g, "Bearer [token]");
  const clipped = redacted.replace(/\s+/g, " ").trim().slice(0, 180);
  return clipped || "download failed";
}
