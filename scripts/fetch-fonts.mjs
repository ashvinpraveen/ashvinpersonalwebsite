import {
  closeSync,
  createWriteStream,
  existsSync,
  mkdirSync,
  openSync,
  readFileSync,
  readSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { mkdir, open, rename, rm } from "node:fs/promises";
import { dirname, join } from "node:path";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fontDir = join(root, "src/assets/fonts/timeless");
const stagingDir = join(fontDir, ".staging");
const statePath = join(fontDir, ".fetch-state");
const generatedPath = join(root, "src/lib/fonts.generated.ts");
const freshMs = 10 * 60 * 1000;

/** Private Blob prefix. Files are never committed. */
const blobPrefix = "fonts/timeless";
const filenames = [
  "TimelessSerifVF.woff2",
  "TimelessSerifItalicVF.woff2",
  "TimelessSansVF.woff2",
];

const fallbackFamilies = ["DM Sans", "system-ui", "sans-serif"];
const quoteFamily = (name) => (name.includes(" ") ? `"${name}"` : name);
const fallbackList = `Display and body fall back to ${fallbackFamilies.map(quoteFamily).join(", ")}. The run club falls back to Fraunces and Outfit.`;

loadEnvFiles();

try {
  await prepareTimelessFonts();
} catch (error) {
  await rm(stagingDir, { recursive: true, force: true });
  await removePartialFonts();
  writeFallbackModule();
  note(
    "fallback",
    `[fonts] Timeless could not be downloaded (${publicReason(error)}). ${fallbackList}`,
  );
}

async function prepareTimelessFonts() {
  const token = process.env.BLOB_READ_WRITE_TOKEN?.trim();

  if (!token) {
    if (fontsReady()) {
      writeLocalModule();
      note(
        "cached",
        "[fonts] BLOB_READ_WRITE_TOKEN is not set. Using Timeless files already present in src/assets/fonts/timeless/.",
      );
      return;
    }
    writeFallbackModule();
    await removePartialFonts();
    note(
      "fallback",
      `[fonts] BLOB_READ_WRITE_TOKEN is not set. Timeless will not be embedded. ${fallbackList}`,
    );
    return;
  }

  if (fontsReady() && fontsAreFresh() && readState() === "embedded") {
    writeLocalModule();
    return;
  }

  try {
    await downloadFonts(token);
    writeLocalModule();
    note("embedded");
  } catch (error) {
    await rm(stagingDir, { recursive: true, force: true });
    if (fontsReady()) {
      writeLocalModule();
      note(
        "cached",
        `[fonts] Timeless could not be downloaded (${publicReason(error)}). Using the copies already in src/assets/fonts/timeless/.`,
      );
      return;
    }
    await removePartialFonts();
    writeFallbackModule();
    note(
      "fallback",
      `[fonts] Timeless could not be downloaded (${publicReason(error)}). ${fallbackList}`,
    );
  }
}

async function downloadFonts(token) {
  const { get } = await import("@vercel/blob");
  await rm(stagingDir, { recursive: true, force: true });
  await mkdir(stagingDir, { recursive: true });
  const downloads = await Promise.allSettled(
    filenames.map((filename) => downloadFont(get, filename, token)),
  );
  const failed = downloads.find((result) => result.status === "rejected");
  if (failed && failed.status === "rejected") throw failed.reason;
  await mkdir(fontDir, { recursive: true });
  for (const filename of filenames) {
    await rename(join(stagingDir, filename), fontPath(filename));
  }
  await rm(stagingDir, { recursive: true, force: true });
}

async function downloadFont(get, filename, token) {
  const pathname = `${blobPrefix}/${filename}`;
  const result = await get(pathname, { access: "private", token, useCache: false });
  if (!result || result.statusCode !== 200 || !result.stream) {
    throw new Error(`${filename} is missing from the private store`);
  }
  const destination = join(stagingDir, filename);
  await pipeline(Readable.fromWeb(result.stream), createWriteStream(destination));
  if (!(await hasWoff2Signature(destination))) {
    throw new Error(`${filename} is not a woff2 font`);
  }
}

